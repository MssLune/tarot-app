interface CardSeed {
  id: string;
  number: number;
  name: string;
  glyph: string;
  correspondence: string;
  element: string;
  axis: string;
  energy: string;
  /** 'mayor' (Arcanos Mayores) o 'menor' (Arcanos Menores). */
  arcanaType: 'mayor' | 'menor';
  suit?: 'bastos' | 'copas' | 'espadas' | 'oros';
  rank?: string;
  rankValue?: number;
  keywords: string[];
  reversedKeywords: string[];
  upright: string;
  reversed: string;
  advice: string;
  /** Frases cortas que enfocan la carta según el tema de la pregunta (amor/trabajo/dinero/salud). */
  loveHint: string;
  workHint: string;
  moneyHint: string;
  healthHint: string;
  /** Ficha de referencia (siempre al derecho), resumida de la guía del usuario. */
  conceptTags: string[];
  yesNo: 'si' | 'no' | 'incierto';
  yesNoReason: string;
  pastText: string;
  presentText: string;
  futureText: string;
  /** Pasado/Presente/Futuro invertido: contenido propio (la guía sólo cubre la posición derecha). */
  pastTextReversed: string;
  presentTextReversed: string;
  futureTextReversed: string;
  /** undefined para el palo de Bastos: la guía no trae correspondencia astrológica para ese palo. */
  astrology?: string;
}

