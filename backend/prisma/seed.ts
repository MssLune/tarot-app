const ALL_CARDS: CardSeed[] = [...CARDS, ...MINOR_CARDS];

async function main() {
  console.log(`Sembrando ${ALL_CARDS.length} cartas (${CARDS.length} Mayores + ${MINOR_CARDS.length} Menores)...`);
  for (const card of ALL_CARDS) {
    const data = {
      number: card.number,
      name: card.name,
      glyph: card.glyph,
      correspondence: card.correspondence,
      element: card.element,
      axis: card.axis,
      energy: card.energy,
      arcanaType: card.arcanaType,
      suit: card.suit,
      rank: card.rank,
      rankValue: card.rankValue,
      keywords: JSON.stringify(card.keywords),
      reversedKeywords: JSON.stringify(card.reversedKeywords),
      upright: card.upright,
      reversed: card.reversed,
      advice: card.advice,
      loveHint: card.loveHint,
      workHint: card.workHint,
      moneyHint: card.moneyHint,
      healthHint: card.healthHint,
      conceptTags: JSON.stringify(card.conceptTags),
      yesNo: card.yesNo,
      yesNoReason: card.yesNoReason,
      pastText: card.pastText,
      presentText: card.presentText,
      futureText: card.futureText,
      pastTextReversed: card.pastTextReversed,
      presentTextReversed: card.presentTextReversed,
      futureTextReversed: card.futureTextReversed,
      astrology: card.astrology,
    };
    await prisma.card.upsert({
      where: { id: card.id },
      update: data,
      create: { id: card.id, ...data },
    });
  }

  console.log(`Sembrando ${SPREADS.length} tiradas...`);
  for (const spread of SPREADS) {
    await prisma.spreadPosition.deleteMany({ where: { spreadId: spread.id } });
    await prisma.spread.upsert({
      where: { id: spread.id },
      update: {
        name: spread.name,
        description: spread.description,
        preset: spread.preset,
        positions: {
          create: spread.positions.map((pos, index) => ({
            id: `${spread.id}-${pos.id}`,
            order: index,
            name: pos.name,
            prompt: pos.prompt,
            x: pos.x,
            y: pos.y,
            rotate: pos.rotate,
          })),
        },
      },
      create: {
        id: spread.id,
        name: spread.name,
        description: spread.description,
        preset: spread.preset,
        positions: {
          create: spread.positions.map((pos, index) => ({
            id: `${spread.id}-${pos.id}`,
            order: index,
            name: pos.name,
            prompt: pos.prompt,
            x: pos.x,
            y: pos.y,
            rotate: pos.rotate,
          })),
        },
      },
    });
  }

  console.log(`Sembrando ${COMBINATIONS.length} combinaciones...`);
  for (const combo of COMBINATIONS) {
    await prisma.cardCombination.upsert({
      where: { id: combo.id },
      update: {
        name: combo.name,
        cardIds: JSON.stringify(combo.cardIds),
        meaning: combo.meaning,
        tone: combo.tone,
      },
      create: {
        id: combo.id,
        name: combo.name,
        cardIds: JSON.stringify(combo.cardIds),
        meaning: combo.meaning,
        tone: combo.tone,
      },
    });
  }

  console.log('Seed completo.');
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
